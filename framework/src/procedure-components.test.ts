import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { compile } from './compiler.js';

test('steps and timeline preserve order, progress, links, and full bodies', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'shoalrun-procedure-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const config = path.join(directory, 'docs.config.yaml');
  const page = path.join(directory, 'content', 'start.mdx');
  const output = path.join(directory, 'dist');
  await mkdir(path.dirname(page));
  await writeFile(config, `schemaVersion: 1\nsite: { title: Procedure test }\npublications:\n  defaults: { channel: production, version: current, language: en }\n  channels: { production: { pathPrefix: "" } }\n  versions: { current: { pathPrefix: "" } }\n  enabled: [{ channel: production, version: current }]\nnavigation: [{ id: start, doc: guide.start }]\n`);
  const frontmatter = `---\nid: guide.start\ntitle: Start\ntype: guide\nsummary: Start here.\nslug: /\nchannel: production\nversion: current\naccess: { policy: public }\n---\n`;
  await writeFile(page, `${frontmatter}\n<Steps>\n<Step title="Create a page">\nAdd [the source](doc:guide.start).\n\n\`\`\`sh\nshoalrun build\n\`\`\`\n</Step>\n<Step title="Check the output">\nOpen the generated page.\n</Step>\n</Steps>\n\n<Steps variant="cards" toc="include" headingLevel="3">\n<Step title="Publish" icon="upload">Deploy the site.</Step>\n</Steps>\n\n<Steps variant="plain">\n<Step title="Review">Check the site.</Step>\n</Steps>\n\n<Timeline current="review">\n<Milestone id="draft" title="Draft" date="2026-09-25">\nWrote the guide.\n</Milestone>\n<Milestone id="review" title="Review" date="2026-09-26">\nChecked [the site](doc:guide.start).\n</Milestone>\n<Milestone id="publish" title="Publish">\nRelease the result.\n</Milestone>\n</Timeline>\n`);
  await compile(config, output);
  const html = await readFile(path.join(output, 'index.html'), 'utf8');
  const markdown = await readFile(path.join(output, 'index.md'), 'utf8');
  assert.match(html, /<ol class="doc-steps doc-steps-rail" role="list"><li>/);
  assert.match(html, /class="doc-steps doc-steps-cards" role="list"/);
  assert.match(html, /class="doc-steps doc-steps-plain"/);
  assert.match(html, /class="doc-step-icon" data-lucide="upload"/);
  assert.match(html, /<section class="doc-timeline" aria-label="Progress timeline">/);
  assert.match(html, /<progress class="doc-timeline-progress" value="1" max="3" aria-label="Milestones complete"><\/progress>/);
  assert.match(html, /class="doc-milestone-current" aria-current="step"/);
  assert.match(html, /<time datetime="2026-09-26">2026-09-26<\/time>/);
  assert.match(html, /<h2 class="doc-step-head doc-step-heading-toc-ignore" id="create-a-page">Create a page<\/h2>/);
  assert.match(html, /<h3 class="doc-step-head" id="publish">/);
  assert.match(html, /<nav class="page-toc"[^]*?<a href="#publish">Publish<\/a>/);
  assert.doesNotMatch(html, /<a href="#create-a-page">Create a page<\/a>/);
  assert.match(html, /class="language-sh"/);
  assert.match(markdown, /1\. ## Create a page/);
  assert.match(markdown, /2\. ## Check the output/);
  assert.match(markdown, /\[the source\]\(\/index\.md\)/);
  assert.match(markdown, /```sh\n\s*shoalrun build\n\s*```/);
  assert.match(markdown, /1 of 3 milestones complete\. Current: Review\./);
  assert.match(markdown, /\*\*Complete: Draft \(2026-09-25\)\*\*/);
  assert.match(markdown, /\*\*Current: Review \(2026-09-26\)\*\*/);
  assert.match(markdown, /\*\*Upcoming: Publish\*\*/);
  assert.doesNotMatch(markdown, /<Steps|<Step|<Timeline|<Milestone/);
  await writeFile(page, `${frontmatter}\n<Steps variant="neon">\n<Step title="Invalid">Nope.</Step>\n</Steps>\n`);
  await assert.rejects(compile(config, output), /<Steps> variant must be rail, cards, or plain/);
  await writeFile(page, `${frontmatter}\n<Steps toc="maybe">\n<Step title="Invalid">Nope.</Step>\n</Steps>\n`);
  await assert.rejects(compile(config, output), /<Steps> toc must be include or ignore/);
  await writeFile(page, `${frontmatter}\n<Steps headingLevel="7">\n<Step title="Invalid">Nope.</Step>\n</Steps>\n`);
  await assert.rejects(compile(config, output), /<Steps> headingLevel must be 2, 3, 4, 5, or 6/);
  await writeFile(page, `${frontmatter}\n<Timeline current="invalid">\n<Milestone id="invalid" date="2026-02-30" title="Invalid">\nNope.\n</Milestone>\n</Timeline>\n`);
  await assert.rejects(compile(config, output), /<Milestone> date must be a real YYYY-MM-DD date/);
  await writeFile(page, `${frontmatter}\n<Steps>\n<Step title="Invalid" />\n</Steps>\n`);
  await assert.rejects(compile(config, output), /<Step> needs body content/);
  await writeFile(page, `${frontmatter}\n<Step title="Loose">No parent.</Step>\n`);
  await assert.rejects(compile(config, output), /<Step> must be directly inside <Steps> or <Walkthrough>/);
});
