import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createCodeHighlighter } from './highlight.js';
import { compile } from './compiler.js';
import { captureSnapshotInputs } from './authoring-snapshot.js';
import { parse as parseHtml } from 'parse5';

const grammar = (keyword = 'publish') => ({ scopeName: 'source.custompy', patterns: [{ match: `\\b${keyword}\\b`, name: 'keyword.control.custompy' }, { include: 'source.python' }] });
const registration = { id: 'custompy', grammar: './custompy.tmLanguage.json', aliases: ['cpy'] };
const config = { theme: 'github-dark', languages: [registration] };
const nodes = (node: any): any[] => [node, ...(node.childNodes ?? []).flatMap(nodes)];
const textOf = (node: any): string => node.nodeName === '#text' ? node.value : (node.childNodes ?? []).map(textOf).join('');

test('a Python-like TextMate grammar and aliases highlight exact source without leaking across projects', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'shoalrun-grammar-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const file = path.join(root, 'custompy.tmLanguage.json');
  await writeFile(file, JSON.stringify(grammar()));
  const first = await createCodeHighlighter(config, path.join(root, 'docs.config.yaml'));
  t.after(() => first.dispose?.());
  const code = 'publish "<hello>"\r\ndef greet():\n    return 42\n';
  const highlighted = first.highlight(code, 'custompy');
  assert.equal(highlighted.map(token => token.text).join(''), code);
  assert.deepEqual(first.highlight(code, 'CPY'), highlighted);
  assert.ok(highlighted.some(token => token.text.includes('publish') && token.color));
  assert.deepEqual(first.dependencies, [file]);
  const ordinary = await createCodeHighlighter({ theme: 'github-dark' });
  assert.deepEqual(ordinary.highlight(code, 'custompy'), [{ text: code }]);
  await writeFile(file, JSON.stringify(grammar('pause')));
  const second = await createCodeHighlighter(config, path.join(root, 'docs.config.yaml'));
  t.after(() => second.dispose?.());
  assert.notDeepEqual(second.highlight(code, 'custompy'), highlighted, 'A grammar edit must not reuse stale token rules.');
  assert.deepEqual(first.highlight(code, 'custompy'), highlighted, 'Another project must not replace this registry.');
});

test('invalid grammar registrations fail clearly rather than silently losing highlighting', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'shoalrun-grammar-errors-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const file = path.join(root, 'custompy.tmLanguage.json');
  const declaring = path.join(root, 'docs.config.yaml');
  await writeFile(file, JSON.stringify(grammar()));
  for (const entry of [{ ...registration, id: 'python' }, { ...registration, aliases: ['py'] }, { ...registration, aliases: ['cpy', 'cpy'] }, { ...registration, id: 'Not lowercase' }, { ...registration, grammar: 'https://example.com/lang.json' }]) await assert.rejects(createCodeHighlighter({ languages: [entry] }, declaring), /registered|lowercase|relative path/);
  await assert.rejects(createCodeHighlighter({ provider: 'none', languages: [registration] }, declaring), /Unsupported highlighting setting/);
  await assert.rejects(createCodeHighlighter({ languages: [registration, { ...registration, id: 'other', aliases: [] }] }, declaring), /scopeName.*already registered/);
  await writeFile(file, JSON.stringify({ ...grammar(), scopeName: 'source.python' }));
  await assert.rejects(createCodeHighlighter(config, declaring), /scopeName.*already registered/);
  await writeFile(file, '{');
  await assert.rejects(createCodeHighlighter(config, declaring), /invalid TextMate JSON/);
  await writeFile(file, JSON.stringify({ scopeName: 'source.custompy' }));
  await assert.rejects(createCodeHighlighter(config, declaring), /patterns array/);
  await rm(file);
  const dependencies: string[] = [];
  await assert.rejects(createCodeHighlighter(config, declaring, { onDependency: file => dependencies.push(file) }), /cannot read grammar/);
  assert.deepEqual(dependencies, [file], 'Failed rebuilds must still discover the missing grammar dependency.');
});

test('inherited grammar paths are watched, captured, and reloaded while Markdown stays unchanged', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'shoalrun-grammar-project-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'shared'));
  await mkdir(path.join(root, 'site/content'), { recursive: true });
  const file = path.join(root, 'shared/custompy.tmLanguage.json');
  const configFile = path.join(root, 'site/docs.config.yaml');
  await writeFile(file, JSON.stringify(grammar()));
  await writeFile(path.join(root, 'shared/base.yaml'), JSON.stringify({ outputs: { html: { highlighting: config, shareImages: false } } }));
  await writeFile(configFile, JSON.stringify({ extends: ['../shared/base.yaml'], schemaVersion: 1, site: { title: 'Grammar test', contentDir: './content' }, publications: { defaults: { channel: 'production', version: 'current', language: 'en' }, channels: { production: {} }, versions: { current: {} }, enabled: [{ channel: 'production', version: 'current', language: 'en' }] } }));
  await writeFile(path.join(root, 'site/content/start.mdx'), '---\nid: guide.start\ntitle: Start\nsummary: Test custom highlighting.\ntype: guide\nchannel: production\nversion: current\nlanguage: en\nslug: /start\naccess: { policy: public }\n---\n\n```cpy\npublish "<hello>"\n```\n');
  const output = path.join(root, 'output');
  const seen: string[] = [];
  const first = await compile(configFile, output, {}, { onDependency: file => seen.push(file) });
  assert.ok(first.dependencies.includes(file));
  assert.ok(seen.includes(file));
  const html = await readFile(path.join(output, 'start/index.html'), 'utf8');
  const markdown = await readFile(path.join(output, 'start.md'), 'utf8');
  assert.match(html, /<span style="color:/);
  const code = nodes(parseHtml(html)).find(node => node.tagName === 'code' && node.attrs?.some((attr: any) => attr.name === 'class' && attr.value === 'language-cpy'));
  assert.equal(textOf(code), 'publish "<hello>"\n', 'Rendered code must retain literal angle brackets rather than interpreting HTML.');
  assert.ok(markdown.includes('```cpy\npublish "<hello>"\n```'));
  const before = await captureSnapshotInputs(configFile);
  assert.ok(before.inputs.some(input => input.file === '../shared/custompy.tmLanguage.json'));
  await writeFile(file, JSON.stringify(grammar('pause')));
  const second = await compile(configFile, output);
  assert.notEqual(second.buildId, first.buildId);
  assert.notEqual(await readFile(path.join(output, 'start/index.html'), 'utf8'), html);
  assert.equal(await readFile(path.join(output, 'start.md'), 'utf8'), markdown);
  const after = await captureSnapshotInputs(configFile);
  assert.notEqual(after.inputs.find(input => input.file.endsWith('custompy.tmLanguage.json'))?.digest, before.inputs.find(input => input.file.endsWith('custompy.tmLanguage.json'))?.digest);
  await writeFile(file, 'invalid JSON');
  const good = await readFile(path.join(output, 'start/index.html'), 'utf8');
  await assert.rejects(compile(configFile, output), /invalid TextMate JSON/);
  assert.equal(await readFile(path.join(output, 'start/index.html'), 'utf8'), good, 'A bad grammar must preserve the last good build.');
});
