import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { compile } from './compiler.js';

test('new components retain their text and destinations in HTML and Markdown', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'shoalrun-components-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const config = path.join(directory, 'docs.config.yaml');
  const page = path.join(directory, 'content', 'start.mdx');
  const output = path.join(directory, 'dist');
  await mkdir(path.dirname(page));
  const configuration = `schemaVersion: 1\nsite: { title: Components test }\ntheme: { mode: system }\nbadges:\n  variants:\n    partner:\n      light: { background: '#f1e9fb', text: '#553078' }\n      dark: { background: '#2a1c3a', text: '#e1c4ff' }\npublications:\n  defaults: { channel: production, version: current, language: en }\n  channels: { production: { pathPrefix: "" } }\n  versions: { current: { pathPrefix: "" } }\n  enabled: [{ channel: production, version: current }]\nnavigation: [{ id: guides, label: Guides, items: [{ id: start, doc: guide.start }] }]\n`;
  await writeFile(config, configuration);
  const frontmatter = `---\nid: guide.start\ntitle: Start\ntype: guide\nsummary: Start here.\nslug: /\nchannel: production\nversion: current\naccess: { policy: public }\n---\n`;
  await writeFile(page, `${frontmatter}\nStatus <Badge variant="success" icon="check">Stable</Badge>, <Badge variant="new">New</Badge>, <Badge variant="partner">Partner</Badge>, and <Math expression="E=mc^2" />. Press <Kbd>⌘</Kbd> + <Kbd>K</Kbd>.\n\n<InfoHint label="Canonical URL">\nThe preferred page address.\n</InfoHint>\n\n<Progress label="Migration tasks" value="3" max="5" />\n\n<ActionLink doc="guide.start" variant="secondary">Read the start</ActionLink>\n\n<DefinitionList filter>\n<Term>Publication</Term>\n<Definition>A versioned page with [more detail](doc:guide.start).</Definition>\n</DefinitionList>\n\n<Math display expression="c^2=a^2+b^2" />\n\n<FileTree>\n<Folder name="docs" icon="folder">\n<File name="start.mdx" doc="guide.start" icon="file-text" />\n</Folder>\n</FileTree>\n`);
  await compile(config, output);
  const html = await readFile(path.join(output, 'index.html'), 'utf8');
  const markdown = await readFile(path.join(output, 'index.md'), 'utf8');
  assert.match(html, /class="doc-badge doc-badge-success"/);
  assert.match(html, /class="doc-badge doc-badge-new">New<\/span>/);
  assert.match(html, /class="doc-badge doc-badge-partner"/);
  assert.match(html, /href="\/assets\/badges\.css"/);
  const badgeStyles = await readFile(path.join(output, 'assets', 'badges.css'), 'utf8');
  assert.match(badgeStyles, /doc-badge-partner\{background:#f1e9fb;color:#553078;border-color:#553078\}/);
  assert.match(badgeStyles, /data-mode=dark.*doc-badge-partner\{background:#2a1c3a;color:#e1c4ff;border-color:#e1c4ff\}/);
  assert.match(html, /<dl class="doc-definition-list">/);
  assert.match(html, /class="doc-definition-list-wrap" data-definition-filter/);
  assert.match(html, /Filter terms and definitions/);
  assert.match(html, /src="\/assets\/table-filter\.js"/);
  assert.match(html, /class="doc-action-link doc-action-secondary"/);
  assert.match(html, /class="doc-file-tree"/);
  assert.match(html, /<kbd class="doc-kbd">⌘<\/kbd>/);
  assert.match(html, /<details class="doc-info-hint"><summary>Canonical URL<\/summary><p>The preferred page address\.<\/p><\/details>/);
  assert.match(html, /Migration tasks: 3 of 5 complete/);
  assert.match(html, /<progress value="3" max="5" aria-label="Migration tasks">/);
  assert.match(html, /<nav class="doc-breadcrumbs" aria-label="Breadcrumb">/);
  assert.match(html, /<span aria-current="page">Start<\/span>/);
  assert.match(html, /<math /);
  assert.match(markdown, /Stable/);
  assert.match(markdown, /New/);
  assert.match(markdown, /Partner/);
  assert.match(markdown, /Read the start.*index\.md/);
  assert.match(markdown, /Publication/);
  assert.match(markdown, /A versioned page with \[more detail\]\(\/index\.md\)\./);
  assert.doesNotMatch(markdown, /Filter terms and definitions/);
  assert.match(markdown, /start\.mdx/);
  assert.match(markdown, /Canonical URL: The preferred page address\./);
  assert.match(markdown, /Migration tasks: 3 of 5 complete\./);
  assert.match(markdown, /Breadcrumbs: Guides > Start/);
  assert.match(markdown, /⌘ \+ K/);
  assert.match(markdown, /E=mc\^2/);
  assert.match(markdown, /c\^2=a\^2\+b\^2/);
  assert.doesNotMatch(markdown, /<Badge|<DefinitionList|<FileTree|<Math/);
  const manifest = JSON.parse(await readFile(path.join(output, 'documents.json'), 'utf8'));
  assert.deepEqual(manifest.documents[0].breadcrumbs, [{ label: 'Guides' }, { label: 'Start', url: '/' }]);
  await writeFile(page, `${frontmatter}\n<DefinitionList>\n<Term>Plain</Term>\n<Definition>Always visible.</Definition>\n</DefinitionList>\n`);
  await compile(config, output);
  const plain = await readFile(path.join(output, 'index.html'), 'utf8');
  assert.match(plain, /<dl class="doc-definition-list"><dt>Plain<\/dt><dd>Always visible\.<\/dd><\/dl>/);
  assert.doesNotMatch(plain, /data-definition-filter|table-filter\.js/);
  await writeFile(page, `${frontmatter}\n<DefinitionList filter="yes">\n<Term>Wrong</Term>\n<Definition>Invalid attribute.</Definition>\n</DefinitionList>\n`);
  await assert.rejects(compile(config, output), /only accepts a bare filter attribute/);
  await writeFile(page, `${frontmatter}\n<Progress label="Migration" value="6" max="5" />\n`);
  await assert.rejects(compile(config, output), /value from 0 through positive max/);
  await writeFile(page, `${frontmatter}\n<Math expression="\\unknownCommand" />\n`);
  await assert.rejects(compile(config, output), /invalid <Math> expression/);
  await writeFile(page, `${frontmatter}\n<Badge variant="missing">Missing</Badge>\n`);
  await assert.rejects(compile(config, output), /unknown <Badge> variant "missing"/);
  await writeFile(config, configuration.replace("text: '#553078'", "text: '#f1e9fb'"));
  await assert.rejects(compile(config, output), /badges\.variants\.partner light: text .* needs 4\.5:1/);
  await writeFile(config, configuration.replace("      dark: { background: '#2a1c3a', text: '#e1c4ff' }\n", ''));
  await assert.rejects(compile(config, output), /badges\.variants\.partner needs dark colors/);
});
