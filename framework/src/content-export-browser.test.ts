import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, cp, mkdir, symlink, readFile, rm, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import puppeteer from 'puppeteer';

test('a plain help drawer loads relocated fragments, images and links from an unrelated app route', async t => {
  const framework = process.env.SHOALRUN_TEST_PACKAGE ?? fileURLToPath(new URL('..', import.meta.url));
  const { exportContent } = await import(pathToFileURL(path.join(framework, 'dist/content-export.js')).href);
  const root = await mkdtemp(path.join(os.tmpdir(), 'shoalrun-help-app-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await cp(path.join(framework, 'examples/help-drawer'), root, { recursive: true });
  await mkdir(path.join(root, 'node_modules/@shoalrun'), { recursive: true });
  await symlink(framework, path.join(root, 'node_modules/@shoalrun/cli'));
  const config = path.join(root, 'docs.config.yaml');
  await writeFile(config, (await readFile(config, 'utf8')).replace('documents: [guide.keys, guide.billing]', 'documents: [guide.keys, guide.billing, guide.rotation]'));
  await mkdir(path.join(root, 'content/rotation'));
  await writeFile(path.join(root, 'content/rotation/settings.svg'), '<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20"><rect width="20" height="20" fill="blue"/></svg>');
  await writeFile(path.join(root, 'content/rotation/rotation.mdx'), '---\nid: guide.rotation\ntitle: Rotate keys\nsummary: Rotate credentials.\nslug: /api-keys\n---\n<Image src="./settings.svg" alt="Rotation settings" />\n\n[Back to keys](doc:guide.keys)\n');
  const keys = path.join(root, 'content/keys.mdx');
  await writeFile(keys, (await readFile(keys, 'utf8')) + '\n[Rotation help](doc:guide.rotation)\n\n## Export anchor\n\n[Jump here](#export-anchor)\n');
  const output = path.join(root, 'public/help');
  await exportContent(config, output, { target: 'app-help' });
  const server = createServer(async (request, response) => {
    const pathname = new URL(request.url!, 'http://localhost').pathname;
    const file = pathname.startsWith('/help/') ? path.join(output, pathname.slice('/help/'.length)) : pathname === '/app.js' ? path.join(root, 'app.js') : path.join(root, 'index.html');
    try {
      const types: Record<string, string> = { '.json': 'application/json', '.js': 'text/javascript', '.html': 'text/html', '.svg': 'image/svg+xml' };
      response.writeHead(200, { 'Content-Type': types[path.extname(file)] ?? 'text/plain' }); response.end(await readFile(file));
    } catch { response.writeHead(404); response.end(); }
  });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise<void>(resolve => { server.closeAllConnections(); server.close(() => resolve()); }));
  const browser = await puppeteer.launch(); t.after(() => browser.close());
  const page = await browser.newPage();
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.setRequestInterception(true);
  page.on('request', request => {
    if (request.url() === 'https://docs.example.com/account') void request.respond({ status: 200, contentType: 'text/html', body: '<h1>Canonical account guide</h1>' });
    else void request.continue();
  });
  const appUrl = `http://127.0.0.1:${(server.address() as any).port}/settings/account`;
  await page.goto(appUrl, { waitUntil: 'networkidle0' });
  await page.focus('[data-help="guide.keys"]');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#content h1')?.textContent === 'API keys');
  assert.equal(await page.evaluate(() => document.activeElement === document.querySelector('#content h1')), true);
  await page.waitForFunction(() => [...document.querySelectorAll('#content img')].length === 2 && [...document.querySelectorAll('#content img')].every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0));
  assert.match(await page.$eval('#content', element => element.textContent!), /Developers/);
  assert.match(await page.$eval('#content', element => element.textContent!), /Operators/);
  const billing = await page.$('#content a[data-export-link]'); assert.ok(billing); await billing.click();
  await page.waitForFunction(() => document.querySelector('#content h1')?.textContent === 'Billing');
  assert.equal(page.url(), appUrl, 'Internal help navigation stays inside the host app');
  assert.match(await page.$eval('#content', element => element.textContent!), /Read the total/);
  assert.match(await page.$eval('#content', element => element.textContent!), /Compare the allowance/);
  await page.click('#content a[data-export-link]');
  await page.waitForFunction(() => document.querySelector('#content h1')?.textContent === 'API keys');
  assert.equal(await page.$eval('#content a[href="https://docs.example.com/account"]', element => element.textContent), 'Full account guide');
  assert.equal(await page.$$eval('#content script, #content [data-component-module]', elements => elements.length), 0);
  const duplicates = await page.$$eval('[id]', elements => elements.map(element => element.id).filter((id, index, ids) => ids.indexOf(id) !== index));
  assert.deepEqual(duplicates, []);
  const originalImage = await page.$eval('#content img', element => (element as HTMLImageElement).src);
  await page.$$eval('#content a', elements => (elements.find(element => element.textContent === 'Rotation help') as HTMLAnchorElement).focus());
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#content h1')?.textContent === 'Rotate keys');
  await page.waitForFunction(() => [...document.querySelectorAll('#content img')].every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0));
  assert.notEqual(await page.$eval('#content img', element => (element as HTMLImageElement).src), originalImage);
  assert.equal(page.url(), appUrl);
  await page.focus('#content a[data-export-link]');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#content h1')?.textContent === 'API keys');
  await page.$$eval('#content a', elements => (elements.find(element => element.textContent === 'Jump here') as HTMLAnchorElement).focus());
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.activeElement?.textContent === 'Export anchor');
  assert.match(await page.evaluate(() => document.activeElement!.id), /^sr-.*-export-anchor$/);
  assert.equal(page.url(), appUrl);
  await page.keyboard.press('Escape');
  assert.equal(await page.$eval('#drawer', element => (element as HTMLElement).hidden), true);
  assert.equal(await page.evaluate(() => (document.activeElement as HTMLElement).dataset.help), 'guide.keys');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#drawer')?.hasAttribute('hidden') === false);
  await page.focus('#content a[href="https://docs.example.com/account"]');
  await Promise.all([page.waitForNavigation(), page.keyboard.press('Enter')]);
  assert.equal(page.url(), 'https://docs.example.com/account');
  assert.deepEqual(errors, []);
});
