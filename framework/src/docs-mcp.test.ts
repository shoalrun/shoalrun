import test from 'node:test';
import assert from 'node:assert/strict';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundledDocumentation, documentationTokens, getDocumentationPage } from './documentation-core.js';

for (const mode of ['legacy', 'auto'] as const) test(`MCP stdio ${mode} clients discover and call documentation tools`, async t => {
  const cli = path.join(path.dirname(fileURLToPath(import.meta.url)), 'cli.js');
  const client = new Client({ name: 'shoalrun-test', version: '1.0.0' }, { versionNegotiation: { mode } });
  const transport = new StdioClientTransport({ command: process.execPath, args: [cli, 'docs', 'mcp'], stderr: 'pipe' });
  let stderr = '';
  transport.stderr?.on('data', chunk => { stderr += String(chunk); });
  t.after(() => client.close());
  await client.connect(transport);
  const tools = await client.listTools();
  assert.deepEqual(tools.tools.map(tool => tool.name).sort(), ['get_outline', 'get_page', 'get_section', 'search_docs']);
  assert.ok(tools.tools.every(tool => tool.annotations?.readOnlyHint));
  const search = await client.callTool({ name: 'search_docs', arguments: { query: 'Organize site navigation', maxTokens: 512 } });
  assert.ok(!search.isError);
  assert.ok(((search.structuredContent as any)?.results as any[]).some(result => result.id === 'guide.navigation-lifecycle'));
  const instruction = (search.structuredContent as any).results[0].read;
  const nextRead = await client.callTool({ name: instruction.tool, arguments: instruction.arguments });
  assert.ok(!nextRead.isError, 'a client can execute the search recommendation without an outline or inferred arguments');
  assert.equal((nextRead.structuredContent as any).budget.truncated, false);
  const narrow = await client.callTool({ name: 'search_docs', arguments: { query: 'Try the page controls', limit: 1 } });
  const recommendation = (narrow.structuredContent as any).results[0];
  assert.equal(recommendation.id, 'guide.agent-friendliness');
  assert.equal(recommendation.read.tool, 'get_section');
  const narrowRead = await client.callTool({ name: recommendation.read.tool, arguments: recommendation.read.arguments });
  assert.ok(!narrowRead.isError);
  assert.match((narrowRead.structuredContent as any).content, /For Reader: Developer/);
  assert.equal((narrowRead.structuredContent as any).budget.truncated, false);
  const vague = await client.callTool({ name: 'search_docs', arguments: { query: 'hide examples for different readers', limit: 3 } });
  const vagueResult = vague.structuredContent as any;
  assert.equal(vagueResult.matchMode, 'mixed');
  assert.equal(vagueResult.results[0].id, 'guide.reader-filters');
  assert.equal(vagueResult.results[0].read.tool, 'get_page');
  // Secondary rankings vary as the bundled corpus grows. Vague queries must
  // retain full-page context rather than recommending narrow sections.
  assert.ok(vagueResult.results.length > 1);
  assert.ok(vagueResult.results.every((hit: any) => hit.read.tool === 'get_page'));
  const setup = await client.callTool({ name: 'search_docs', arguments: { query: 'Set up an MCP client and check token limits', limit: 1 } });
  const setupResult = setup.structuredContent as any;
  assert.equal(setupResult.matchMode, 'partial');
  assert.equal(setupResult.results[0].id, 'guide.mcp');
  const setupInstruction = setupResult.results[0].read;
  assert.equal(setupInstruction.tool, 'get_page');
  const setupRead = await client.callTool({ name: setupInstruction.tool, arguments: setupInstruction.arguments });
  assert.equal((setupRead.structuredContent as any).budget.truncated, false);
  assert.match((setupRead.structuredContent as any).content, /256 through 100000/);
  const prerequisiteSearch = await client.callTool({ name: 'search_docs', arguments: { query: 'Mark sections and add an entry choice', limit: 1 } });
  const prerequisite = (prerequisiteSearch.structuredContent as any).results[0];
  assert.equal(prerequisite.id, 'guide.reader-filters');
  assert.equal(prerequisite.read.tool, 'get_page', 'a matching heading without a standalone declaration retains prerequisite context');
  const complete = await client.callTool({ name: prerequisite.read.tool, arguments: prerequisite.read.arguments });
  assert.equal((complete.structuredContent as any).budget.truncated, false);
  assert.match((complete.structuredContent as any).content, /facets:/);
  assert.match((complete.structuredContent as any).content, /<ReaderSection audience="ui">/);
  const read = await client.callTool({ name: 'get_page' , arguments: { id: 'guide.navigation-lifecycle', maxTokens: 256 } });
  assert.ok(!read.isError);
  const expected = await getDocumentationPage(bundledDocumentation, 'guide.navigation-lifecycle', { maxTokens: 256 });
  assert.deepEqual(read.structuredContent, expected);
  assert.equal(read.content[0].type, 'text');
  if (read.content[0].type === 'text') assert.ok(documentationTokens(read.content[0].text) <= 256);
  for (const [id, code] of [['guide.missing', 'unknown_page'], ['', 'invalid_input']]) {
    const failure = await client.callTool({ name: 'get_page', arguments: { id } });
    assert.equal(failure.isError, true);
    assert.equal(((failure.structuredContent as any)?.error as any).code, code);
  }
  const outline = await client.callTool({ name: 'get_outline', arguments: { id: 'guide.navigation-lifecycle', maxTokens: 100_000 } });
  assert.ok(!outline.isError);
  const section = (outline.structuredContent as any).sections[0];
  const part = await client.callTool({ name: 'get_section', arguments: { id: 'guide.navigation-lifecycle', section: section.id, maxTokens: 100_000 } });
  assert.ok(!part.isError);
  assert.equal((part.structuredContent as any).section.digest, section.digest);
  assert.equal((part.structuredContent as any).budget.truncated, false);
  assert.equal(stderr, '');
});

test('MCP site selection reads the chosen output and reports missing and corrupt indexes as tool failures', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'shoalrun-mcp-site-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const doc = { id: 'custom.page', title: 'Site marker', url: '/page', markdownUrl: '/page.md', variant: { channel: 'production', version: 'current', language: 'en' } };
  await writeFile(path.join(directory, 'documents.json'), JSON.stringify({ schemaVersion: 1, documents: [doc] }));
  await writeFile(path.join(directory, 'page.md'), '# A different built site\n');
  const client = new Client({ name: 'site-test', version: '1.0.0' });
  const cli = path.join(path.dirname(fileURLToPath(import.meta.url)), 'cli.js');
  t.after(() => client.close());
  await client.connect(new StdioClientTransport({ command: process.execPath, args: [cli, 'docs', 'mcp', '--site', directory], stderr: 'pipe' }));
  const page = await client.callTool({ name: 'get_page', arguments: { id: doc.id } });
  assert.equal((page.structuredContent as any).content, '# A different built site\n');
  const missing = await client.callTool({ name: 'search_docs', arguments: { query: 'marker' } });
  assert.equal(missing.isError, true);
  assert.equal((missing.structuredContent as any).error.code, 'missing_index');
  await writeFile(path.join(directory, 'search-index.json'), '{bad');
  const corrupt = await client.callTool({ name: 'search_docs', arguments: { query: 'marker' } });
  assert.equal(corrupt.isError, true);
  assert.equal((corrupt.structuredContent as any).error.code, 'internal_error');
});
