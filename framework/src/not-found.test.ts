import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm, cp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { buildVercel } from './vercel.js';
import { createSiteServer } from './server.js';

test('missing pages retain 404 with recovery links, Markdown, HEAD, and existing HTML twins', async t => {
  const directory = await mkdtemp(path.join(tmpdir(), 'shoalrun-404-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await mkdir(path.join(directory, 'docs/guide'), { recursive: true });
  await writeFile(path.join(directory, 'docs/guide/index.html'), '<h1>Guide</h1>');
  await writeFile(path.join(directory, 'docs/search-index.json'), '[]');
  await writeFile(path.join(directory, 'documents.json'), JSON.stringify({ basePath: '/docs', documents: [{ url: '/docs/guide', markdownUrl: '/docs/guide.md' }] }));
  await writeFile(path.join(directory, 'resource-headers.json'), JSON.stringify({ '/docs/search-index.json': { 'Content-Type': 'application/json' } }));
  const server = await createSiteServer(directory);
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
  const address = server.address();
  assert.ok(address && typeof address !== 'string');
  const origin = `http://127.0.0.1:${address.port}`;
  const missing = await fetch(`${origin}/missing`);
  assert.equal(missing.status, 404);
  assert.equal(missing.headers.get('x-robots-tag'), 'noindex');
  const html = await missing.text();
  assert.match(html, /<ul><li><a[^>]+><span class="label">Go to homepage/);
  for (const href of ['/docs/llms.txt', '/docs/search-index.json', '/docs/guide']) assert.ok(html.includes(`href="${href}"`));
  const markdown = await fetch(`${origin}/docs/guide.md`);
  assert.equal(markdown.status, 404);
  assert.equal(markdown.headers.get('link'), '</docs/guide>; rel="alternate"; type="text/html"');
  assert.match(markdown.headers.get('content-type')!, /text\/markdown/);
  assert.match(await markdown.text(), /\[Read the HTML page\]\(\/docs\/guide\)/);
  const negotiated = await fetch(`${origin}/missing`, { headers: { Accept: 'text/markdown' } });
  assert.equal(negotiated.status, 404);
  const recovery = await negotiated.text();
  assert.match(recovery, /^# 404/);
  assert.match(recovery, /\/docs\/llms\.min\.txt/);
  assert.match(recovery, /\/docs\/search-index\.min\.json/);
  assert.doesNotMatch(recovery, /\/search-index\.json/);
  const negotiatedTwin = await fetch(`${origin}/docs/guide/`, { headers: { Accept: 'text/markdown' } });
  assert.equal(negotiatedTwin.status, 404);
  assert.match(await negotiatedTwin.text(), /\[Read the HTML page\]\(\/docs\/guide\)/);
  const htmlOnly = await fetch(`${origin}/missing`, { headers: { Accept: 'text/markdown;q=0, text/html' } });
  assert.match(htmlOnly.headers.get('content-type')!, /text\/html/);
  const head = await fetch(`${origin}/missing.md`, { method: 'HEAD' });
  assert.equal(head.status, 404);
  assert.equal(await head.text(), '');
  assert.equal((await fetch(`${origin}/docs/guide/`)).status, 200);
  await mkdir(path.join(directory, 'docs/broken.md/index.html'), { recursive: true });
  const failure = await fetch(`${origin}/docs/broken.md/`);
  assert.equal(failure.status, 500);
  assert.equal(await failure.text(), 'Internal server error\n');
  await rm(path.join(directory, 'docs/guide/index.html'));
  assert.doesNotMatch(await (await fetch(`${origin}/docs/guide.md`)).text(), /Read the HTML page/);
});

test('Vercel emits 404 recovery files and routes after filesystem lookup', async t => {
  const directory = await mkdtemp(path.join(tmpdir(), 'shoalrun-404-vercel-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await cp(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../example-configs/minimal'), directory, { recursive: true });
  const config = path.join(directory, 'docs.config.yaml');
  await writeFile(config, (await readFile(config, 'utf8')).replace('  title: Acme handbook', '  title: Acme handbook\n  basePath: /docs'));
  const output = path.join(directory, 'output');
  await writeFile(config, `${await readFile(config, 'utf8')}\ntheme: { preset: ledger, palette: ink, mode: light }\n`);
  await buildVercel(config, output);
  const deployment = JSON.parse(await readFile(path.join(output, 'config.json'), 'utf8'));
  const filesystem = deployment.routes.findIndex((route: any) => route.handle === 'filesystem');
  const fallbacks = deployment.routes.slice(filesystem + 1);
  assert.ok(fallbacks.length >= 3);
  assert.ok(fallbacks.some((route: any) => route.headers.Link?.includes('type="text/html"')));
  assert.ok(fallbacks.every((route: any) => route.status === 404));
  assert.equal(fallbacks.at(-1).dest, '/docs/404.html');
  assert.ok(fallbacks.some((route: any) => route.dest === '/docs/404.md' && route.has));
  assert.equal(deployment.overrides['docs/404.md'].contentType, 'text/markdown; charset=utf-8');
  const directError = deployment.routes.find((route: any) => route.src === '^/docs/404\\.md$' && route.continue);
  assert.equal(directError.headers['X-Robots-Tag'], 'noindex');
  const manifest = JSON.parse(await readFile(path.join(output, 'static/documents.json'), 'utf8'));
  assert.ok(manifest.documents.every((document: any) => !document.markdownUrl.endsWith('/404.md')));
  const errorHtml = await readFile(path.join(output, 'static/docs/404.html'), 'utf8');
  assert.match(errorHtml, /data-theme="ledger" data-palette="ink"/);
  assert.match(errorHtml, /href="\/docs\/assets\/theme.css"/);
  assert.match(errorHtml, /href="\/docs\/llms.txt"/);
  assert.match(await readFile(path.join(output, 'static/docs/404.md'), 'utf8'), /\[Documentation index\]\(\/docs\/llms.min.txt\)/);
});
